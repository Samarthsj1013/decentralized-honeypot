
from pathlib import Path
from typing import Literal

import joblib
import pandas as pd
from fastapi import HTTPException, status
from pydantic import BaseModel

from app.events.models import HoneypotEvent
from app.events.store import EventStore


PROJECT_ROOT = Path(__file__).resolve().parents[3]
MODEL_PATH = PROJECT_ROOT / "experiments" / "results" / "behavior_model.joblib"

FEATURE_COLUMNS = [
    "event_count",
    "unique_decoys_accessed",
    "unique_actions",
    "login_attempts",
    "database_queries",
    "interactions_per_minute",
    "category_coverage",
]

DECOY_TYPES = {
    "decoy-finance-001": "file",
    "decoy-credential-001": "credential",
    "decoy-database-001": "database_record",
}


class MLBehaviorAssessment(BaseModel):
    """Machine-learning assessment of one synthetic actor."""

    actor_id: str
    event_count: int
    predicted_class: Literal["benign", "suspicious"]
    suspicious_probability: float
    model_name: str = "RandomForestClassifier"
    assessment_type: str = "synthetic_model_inference"
    features: dict[str, int | float]
    limitations: list[str] = [
        "Model trained on synthetic scenarios only.",
        "Prediction is not proof of malicious activity.",
        "Probability is a model score, not a calibrated real-world risk.",
    ]


class MLIntelligenceService:
    """Loads a locally trained model and assesses actor event histories."""

    def __init__(self, store: EventStore) -> None:
        self._store = store

    @staticmethod
    def _load_model():
        if not MODEL_PATH.exists():
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail=(
                    "Trained model not found. Run "
                    "'python simulator/train_model.py' first."
                ),
            )

        try:
            # Only load the model artifact generated by our own
            # trusted training script. Never load untrusted joblib files.
            return joblib.load(MODEL_PATH)
        except Exception as exc:
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="The trained model could not be loaded.",
            ) from exc

    def _get_actor_events(self, actor_id: str) -> list[HoneypotEvent]:
        events = [
            event
            for event in self._store.list_events()
            if event.actor_id == actor_id
        ]

        if not events:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="No recorded events found for this actor",
            )

        return sorted(events, key=lambda event: event.timestamp)

    @staticmethod
    def _extract_features(
        events: list[HoneypotEvent],
    ) -> dict[str, int | float]:
        event_count = len(events)
        unique_decoys = {event.decoy_id for event in events}
        unique_actions = {event.action for event in events}

        login_attempts = sum(
            event.action == "attempt_login" for event in events
        )
        database_queries = sum(
            event.action == "query" for event in events
        )

        decoy_categories = {
            DECOY_TYPES[event.decoy_id]
            for event in events
            if event.decoy_id in DECOY_TYPES
        }

        elapsed_minutes = (
            events[-1].timestamp - events[0].timestamp
        ).total_seconds() / 60.0

        # Prevent division by zero for events recorded at nearly
        # the same time. This is a feature-engineering convention.
        elapsed_minutes = max(elapsed_minutes, 1.0 / 60.0)

        interactions_per_minute = min(
            event_count / elapsed_minutes,
            40.0,
        )

        return {
            "event_count": event_count,
            "unique_decoys_accessed": len(unique_decoys),
            "unique_actions": len(unique_actions),
            "login_attempts": login_attempts,
            "database_queries": database_queries,
            "interactions_per_minute": round(
                interactions_per_minute, 4
            ),
            "category_coverage": len(decoy_categories),
        }

    def analyze_actor(self, actor_id: str) -> MLBehaviorAssessment:
        events = self._get_actor_events(actor_id)
        features = self._extract_features(events)

        model = self._load_model()
        feature_frame = pd.DataFrame(
            [features],
            columns=FEATURE_COLUMNS,
        )

        prediction = str(model.predict(feature_frame)[0])
        probabilities = model.predict_proba(feature_frame)[0]
        classes = list(model.classes_)

        if "suspicious" not in classes:
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="The trained model has no suspicious class.",
            )

        suspicious_index = classes.index("suspicious")
        suspicious_probability = float(
            probabilities[suspicious_index]
        )

        return MLBehaviorAssessment(
            actor_id=actor_id,
            event_count=len(events),
            predicted_class=prediction,
            suspicious_probability=round(
                suspicious_probability, 4
            ),
            features=features,
        )


from app.events.store import event_store

ml_intelligence_service = MLIntelligenceService(event_store)
